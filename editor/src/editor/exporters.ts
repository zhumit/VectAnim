/**
 * Exporters: JSON / SVG / PNG.
 *
 * SVG export is for documentation and delivery review; PNG export is for
 * screenshots and reports. Both are static snapshots based on the "current
 * variable values" and stay consistent with the WPF runtime rendering.
 */

import { t } from '../i18n';
import type { VectAnimDocument } from '../schema/types';
import type { VariableResolver } from '../schema/valueRef';
import { resolveDocument, type ResolvedShape } from '../engine/resolve';
import { Canvas2DRenderer } from '../engine/canvasRenderer';
import { parseCssColor, toCssColor } from '../engine/color';

function escapeXml(text: string): string {
  return text.replace(/[<>&"']/g, (char) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[char] ?? char));
}

function number(value: number): string {
  const rounded = Math.round(value * 1000) / 1000;
  return String(rounded);
}

function paintAttributes(color: string | null, key: 'fill' | 'stroke'): string {
  if (!color) return `${key}="none"`;
  const rgba = parseCssColor(color);
  if (!rgba) return `${key}="none"`;
  const css = `rgb(${rgba.r},${rgba.g},${rgba.b})`;
  const opacity = rgba.a < 1 ? ` ${key}-opacity="${number(rgba.a)}"` : '';
  return `${key}="${css}${opacity}`;
}

function shapeTransform(shape: ResolvedShape): string {
  const { angle, cx, cy, sx, sy, tx, ty } = shape.transform;
  const parts: string[] = [];
  if (tx !== 0 || ty !== 0) parts.push(`translate(${number(tx)} ${number(ty)})`);
  if (angle !== 0) parts.push(`rotate(${number(angle)} ${number(cx)} ${number(cy)})`);
  if (sx !== 1 || sy !== 1) {
    parts.push(`translate(${number(cx)} ${number(cy)})`, `scale(${number(sx)} ${number(sy)})`, `translate(${number(-cx)} ${number(-cy)})`);
  }
  return parts.length ? ` transform="${parts.join(' ')}"` : '';
}

function strokeAttributes(shape: ResolvedShape): string {
  const attributes: string[] = [paintAttributes(shape.stroke, 'stroke')];
  if (shape.stroke) {
    attributes.push(`stroke-width="${number(shape.strokeThickness)}"`);
    attributes.push(`stroke-linecap="${shape.lineCap === 'Round' ? 'round' : shape.lineCap === 'Square' ? 'square' : 'butt'}"`);
    attributes.push(`stroke-linejoin="${shape.lineJoin === 'Round' ? 'round' : shape.lineJoin === 'Bevel' ? 'bevel' : 'miter'}"`);
  }
  return attributes.join(' ');
}

function shapeToSvg(shape: ResolvedShape): string {
  const opacity = shape.opacity < 1 ? ` opacity="${number(shape.opacity)}"` : '';
  const common = `${paintAttributes(shape.fill, 'fill')} ${strokeAttributes(shape)}${opacity}`;
  const geometry = shape.geometry;

  switch (geometry.kind) {
    case 'line':
      return `<line x1="${number(geometry.x1)}" y1="${number(geometry.y1)}" x2="${number(geometry.x2)}" y2="${number(geometry.y2)}" ${common}${shapeTransform(shape)} />`;
    case 'rect': {
      const radius = geometry.rx > 0 || geometry.ry > 0 ? ` rx="${number(geometry.rx)}" ry="${number(geometry.ry)}"` : '';
      return `<rect x="${number(geometry.x)}" y="${number(geometry.y)}" width="${number(geometry.width)}" height="${number(geometry.height)}"${radius} ${common}${shapeTransform(shape)} />`;
    }
    case 'ellipse':
      return `<ellipse cx="${number(geometry.cx)}" cy="${number(geometry.cy)}" rx="${number(geometry.rx)}" ry="${number(geometry.ry)}" ${common}${shapeTransform(shape)} />`;
    case 'polygon': {
      const points = geometry.points.map((point) => `${number(point.x)},${number(point.y)}`).join(' ');
      const tag = geometry.closed ? 'polygon' : 'polyline';
      return `<${tag} points="${points}" ${common}${shapeTransform(shape)} />`;
    }
    case 'path': {
      const offset = geometry.offsetX || geometry.offsetY
        ? `translate(${number(geometry.offsetX)} ${number(geometry.offsetY)})`
        : '';
      const transform = shapeTransform(shape);
      const combined = offset
        ? ` transform="${offset}${transform ? ` ${transform.slice(' transform="'.length, -1)}` : ''}"`
        : transform;
      return `<path d="${escapeXml(geometry.data)}" ${common}${combined} fill-rule="nonzero" />`;
    }
    default:
      return '';
  }
}

export function documentToSvg(document: VectAnimDocument, resolver: VariableResolver): string {
  const shapes = resolveDocument(document, resolver);
  const background = toCssColor(document.Canvas.Background, 'transparent');
  const body = shapes
    .filter((shape) => shape.visible)
    .map((shape) => `    ${shapeToSvg(shape)}`)
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${document.Canvas.Width}" height="${document.Canvas.Height}" viewBox="0 0 ${document.Canvas.Width} ${document.Canvas.Height}">`,
    `  <title>${escapeXml(document.Meta?.Title ?? 'VectAnim')}</title>`,
    `  <desc>Generated by VectAnim Editor</desc>`,
    `  <rect width="${document.Canvas.Width}" height="${document.Canvas.Height}" fill="${background}" />`,
    body,
    '</svg>',
    '',
  ].join('\n');
}

export function documentToPngBlob(document: VectAnimDocument, resolver: VariableResolver, scale = 2): Promise<Blob> {
  const canvas = window.document.createElement('canvas');
  const renderer = new Canvas2DRenderer(canvas);
  renderer.resize(document.Canvas.Width * scale, document.Canvas.Height * scale, 1);
  const shapes = resolveDocument(document, resolver);
  renderer.render(shapes, document.Canvas, { zoom: scale, offsetX: 0, offsetY: 0 }, {});

  return new Promise((resolve, reject) => {
    canvas.toBlob((blob) => {
      if (blob) resolve(blob);
      else reject(new Error(t('engine.export.pngFailed')));
    }, 'image/png');
  });
}
